export function t(
  key: string,
  locale: Locale,
  params?: Record<string, string | number>,
  fallback?: string,
): string {
  let text = translations[locale]?.[key] || translations.en[key] || fallback || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}
